export const messages: Record<Locale, Record<TranslationKey, string>> = {
  en,
  zh,
}

function interpolate(template: string, values?: MessageValues): string {
  if (!values) {
    return template
  }

  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = values[key]
    return value === undefined ? `{${key}}` : String(value)
  })
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values?: MessageValues,
) {
  const template = messages[locale][key] ?? messages.en[key] ?? key
  return interpolate(template, values)
}

export function getStatusLabel(locale: Locale, status?: string) {
  switch (status) {
    case "running":
      return translate(locale, "status.running")
    case "starting":
      return translate(locale, "status.starting")
    case "stopping":
      return translate(locale, "status.stopping")
    case "stopped":
      return translate(locale, "status.stopped")
    case "error":
      return translate(locale, "status.error")
    default:
      return translate(locale, "status.unknown")
  }
}

export function getLocaleTag(locale: Locale) {
  return locale === "zh" ? "zh-CN" : "en-US"
}

export type { TranslationKey, MessageValues }
